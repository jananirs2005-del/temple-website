    document.getElementById("navGallery")
        .textContent = data.galleryNav;

    document.getElementById("navContact")
        .textContent = data.contactNav;


    /* Hero */

    document.getElementById("welcomeText")
        .textContent = data.welcome;

    document.getElementById("heroTempleName")
        .textContent = data.name;

    document.getElementById("heroSubName")
        .textContent = data.subName;

    document.getElementById("heroLocation")
        .textContent = data.location;

    document.getElementById("heroDescription")
        .textContent = data.description;

    document.getElementById("heroButton")
        .textContent = data.button;


    /* About */

    document.getElementById("aboutTitle")
        .textContent = data.aboutTitle;

    document.getElementById("aboutText1")
        .textContent = data.about1;

    document.getElementById("aboutText2")
        .textContent = data.about2;

    document.getElementById("aboutText3")
        .textContent = data.about3;


    /* Pooja */

    document.getElementById("poojaTitle")
        .textContent = data.poojaTitle;

